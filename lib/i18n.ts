export function isLanguage(value: unknown): value is Language {
  return languages.some((language) => language === value);
}

export function normalizeLanguage(value: string | undefined): Language | null {
  if (!value) {
    return null;
  }

  const normalized = value.toLowerCase();
  if (normalized.startsWith("zh")) {
    // Traditional for Hant / TW / HK / MO, Simplified otherwise (Hans, CN, SG).
    if (
      normalized.includes("hant") ||
      normalized.includes("tw") ||
      normalized.includes("hk") ||
      normalized.includes("mo")
    ) {
      return "zh-Hant";
    }
    return "zh-Hans";
  }

  const exactMatch = languages.find((language) => language.toLowerCase() === normalized);
  if (exactMatch) {
    return exactMatch;
  }

  const baseLanguage = normalized.split("-")[0];
  return languages.find((language) => language.toLowerCase() === baseLanguage) ?? null;
}